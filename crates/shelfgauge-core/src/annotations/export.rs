//! The Markdown of a book's bookmarks, quotes and notes, in two forms.
//!
//! - [`linked`]: the library's export files (`.shelfgauge/annotations/`): the
//!   bookmarks, then the quotes grouped by section, then the notes on places, each
//!   with a link to its place in the library's reader;
//! - [`unlinked`]: what a reader exports or copies from the reader's Quotes tab
//!   (library and hub reader): the quotes and the notes on places only, as plain
//!   text, without links. A quote is its text as it is, its note a paragraph starting
//!   with `Note: `, and the records are divided by a line `***`.
//!
//! [`copy_text`] is one quote in the unlinked form, for a message.

use std::fmt::Write as _;

use super::text;

/// The first line of every file of the library's export (never of [`unlinked`]).
pub const MARKER: &str = "<!-- generated by shelfgauge, edits are overwritten -->";

/// The longest file name stem in code points (before the suffix and extension).
const MAX_STEM_CHARS: usize = 120;

/// The line between two records of the unlinked form.
const SEPARATOR: &str = "***";

/// The book an export is about.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ExportHead {
    /// The title.
    pub title: String,
    /// The authors, joined with `, `.
    pub authors: String,
}

/// What an [`ExportItem`] is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExportKind {
    /// A bookmark: a place without quoted text.
    Bookmark,
    /// A quote, maybe with a note.
    Quote,
    /// A note on a place (no quoted text).
    PlaceNote,
}

/// One annotation of an export, in book order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExportItem<'a> {
    /// What it is.
    pub kind: ExportKind,
    /// The quoted text; empty for bookmarks and notes on places.
    pub text: &'a str,
    /// The note; blank counts as none.
    pub note: Option<&'a str>,
    /// The section title at its start (quotes are grouped by it).
    pub section_title: Option<&'a str>,
    /// The label of a bookmark or of a note's place
    /// ([`label`](super::lists::label)).
    pub label: String,
    /// The link to its place ([`linked`] only).
    pub href: String,
    /// Whether its place was not found in the book ([`linked`] only).
    pub lost: bool,
}

impl ExportItem<'_> {
    fn note(&self) -> Option<&str> {
        self.note.filter(|n| !n.trim().is_empty())
    }
}

/// The library's export of a book: [`MARKER`], title and authors, a warning for an
/// `orphan` (no book in the library has this content any more), the bookmarks, the
/// quotes grouped by section, each with its note and a link, then the notes on places,
/// each with a link to its place. Quotes and notes are plain text paragraphs, not
/// Markdown block quotes.
pub fn linked(head: &ExportHead, orphan: bool, items: &[ExportItem]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{MARKER}\n");
    title(&mut out, head);
    if orphan {
        let _ = writeln!(
            out,
            "**Place in the book not found:** the book's file has changed or is no \
             longer in the library. The quotes are kept; the links may not work.\n"
        );
    }
    let bookmarks = of_kind(items, ExportKind::Bookmark);
    let quotes = of_kind(items, ExportKind::Quote);
    let notes = of_kind(items, ExportKind::PlaceNote);
    if !bookmarks.is_empty() {
        let _ = writeln!(out, "## Bookmarks\n");
        for bookmark in bookmarks {
            let _ = writeln!(
                out,
                "- [{}]({})",
                inline(&bookmark.label).replace(']', "\\]"),
                bookmark.href
            );
        }
        out.push('\n');
    }
    if !quotes.is_empty() {
        let _ = writeln!(out, "## Quotes\n");
        let mut section: Option<Option<&str>> = None;
        for quote in quotes {
            if section != Some(quote.section_title) {
                if let Some(title) = quote.section_title {
                    let _ = writeln!(out, "### {}\n", inline(title));
                }
                section = Some(quote.section_title);
            }
            let _ = writeln!(out, "{}\n", plain(quote.text.trim()));
            if let Some(note) = quote.note() {
                let _ = writeln!(out, "{}\n", plain(note.trim()));
            }
            let place = if quote.lost {
                "place not found"
            } else {
                "open"
            };
            let _ = writeln!(out, "[{place}]({})\n", quote.href);
        }
    }
    if !notes.is_empty() {
        let _ = writeln!(out, "## Notes\n");
        for note in notes {
            let _ = writeln!(out, "{}\n", plain(note.note.unwrap_or("").trim()));
            let place = if note.lost {
                "place not found".to_owned()
            } else {
                inline(&note.label)
            };
            let _ = writeln!(out, "[{}]({})\n", place.replace(']', "\\]"), note.href);
        }
    }
    finish(out)
}

/// A book's quotes and notes on places as plain text with Markdown headings, without
/// links and bookmarks: title and authors, `## Quotes` grouped by `### section`, each
/// quote's text as it is and its note as a paragraph starting with `Note: `, then
/// `## Notes`, each the start of its place and the note; records divided by `***`.
///
/// # Examples
///
/// ```
/// use shelfgauge_core::annotations::export::{ExportHead, ExportItem, ExportKind, unlinked};
///
/// let head = ExportHead { title: "The Book".into(), authors: "A. Author".into() };
/// let quote = |text: &'static str, note: Option<&'static str>| ExportItem {
///     kind: ExportKind::Quote,
///     text,
///     note,
///     section_title: Some("Chapter 1"),
///     label: String::new(),
///     href: String::new(),
///     lost: false,
/// };
/// let md = unlinked(&head, &[quote("First.", Some("Mine")), quote("Second.", None)]);
/// assert_eq!(
///     md,
///     "# The Book\n\nA. Author\n\n## Quotes\n\n### Chapter 1\n\n\
///      First.\n\nNote: Mine\n\n***\n\nSecond.\n"
/// );
/// ```
pub fn unlinked(head: &ExportHead, items: &[ExportItem]) -> String {
    let mut out = String::new();
    title(&mut out, head);
    let quotes = of_kind(items, ExportKind::Quote);
    let notes = of_kind(items, ExportKind::PlaceNote);
    if !quotes.is_empty() {
        let _ = writeln!(out, "## Quotes\n");
        let mut section: Option<Option<&str>> = None;
        for (i, quote) in quotes.into_iter().enumerate() {
            if i > 0 {
                let _ = writeln!(out, "{SEPARATOR}\n");
            }
            if section != Some(quote.section_title) {
                if let Some(title) = quote.section_title {
                    let _ = writeln!(out, "### {}\n", inline(title));
                }
                section = Some(quote.section_title);
            }
            let _ = writeln!(out, "{}\n", plain(quote.text.trim()));
            note_paragraph(&mut out, quote.note());
        }
    }
    if !notes.is_empty() {
        let _ = writeln!(out, "## Notes\n");
        for (i, note) in notes.into_iter().enumerate() {
            if i > 0 {
                let _ = writeln!(out, "{SEPARATOR}\n");
            }
            let place = inline(&note.label);
            if !place.is_empty() {
                let _ = writeln!(out, "{place}\n");
            }
            note_paragraph(&mut out, note.note());
        }
    }
    finish(out)
}

/// One quote for a message: its text, its note as a paragraph starting with `Note: `,
/// and `— <Authors>, <Title>`.
///
/// # Examples
///
/// ```
/// use shelfgauge_core::annotations::export::{ExportHead, copy_text};
///
/// let head = ExportHead { title: "The Book".into(), authors: "A. Author".into() };
/// assert_eq!(
///     copy_text(&head, "It was a dark night.", Some("Mine")),
///     "It was a dark night.\n\nNote: Mine\n\n— A. Author, The Book"
/// );
/// assert_eq!(copy_text(&head, "Quoted.", None), "Quoted.\n\n— A. Author, The Book");
/// ```
pub fn copy_text(head: &ExportHead, text: &str, note: Option<&str>) -> String {
    let mut out = format!("{}\n\n", plain(text.trim()));
    note_paragraph(&mut out, note.filter(|n| !n.trim().is_empty()));
    let source = [inline(&head.authors), inline(&head.title)]
        .into_iter()
        .filter(|s| !s.is_empty())
        .collect::<Vec<_>>()
        .join(", ");
    if !source.is_empty() {
        let _ = write!(out, "— {source}");
    }
    out.trim_end().to_owned()
}

/// The file name of a book's [`unlinked`] export: `<Authors> — <Title> — quotes.md`,
/// safe on every platform.
///
/// # Examples
///
/// ```
/// use shelfgauge_core::annotations::export::{ExportHead, quotes_file_name};
///
/// let head = ExportHead { title: "A/B: C?".into(), authors: "Lev Tolstoy".into() };
/// assert_eq!(quotes_file_name(&head), "Lev Tolstoy — A_B_ C_ — quotes.md");
/// ```
pub fn quotes_file_name(head: &ExportHead) -> String {
    format!("{} — quotes.md", file_stem(&head.title, &head.authors))
}

/// The stem of a book's export file names: `<Authors> — <Title>` (or the title
/// alone), safe on every platform, at most 120 code points, `Untitled` when nothing
/// is left.
///
/// # Examples
///
/// ```
/// use shelfgauge_core::annotations::export::file_stem;
///
/// assert_eq!(file_stem("War and Peace", "Lev Tolstoy"), "Lev Tolstoy — War and Peace");
/// assert_eq!(file_stem("CON", ""), "_CON");
/// assert_eq!(file_stem("...", ""), "Untitled");
/// ```
pub fn file_stem(title: &str, authors: &str) -> String {
    let stem = match (authors.trim(), title.trim()) {
        ("", title) => title.to_owned(),
        (authors, title) => format!("{authors} — {title}"),
    };
    let mut stem = sanitize(&stem);
    if text::char_len(&stem) > MAX_STEM_CHARS {
        stem = text::first_chars(&stem, MAX_STEM_CHARS)
            .trim_end_matches([' ', '.'])
            .to_owned();
    }
    if stem.is_empty() {
        stem = "Untitled".to_owned();
    }
    stem
}

/// Replaces characters that are not allowed (or not safe) in file names, collapses
/// whitespace, and avoids Windows device names and names starting with a dot.
///
/// # Examples
///
/// ```
/// use shelfgauge_core::annotations::export::sanitize;
///
/// assert_eq!(sanitize(" a/b:\tc. "), "a_b_ c");
/// assert_eq!(sanitize("nul"), "_nul");
/// ```
pub fn sanitize(name: &str) -> String {
    let replaced: String = name
        .chars()
        .map(|c| match c {
            '<' | '>' | ':' | '"' | '/' | '\\' | '|' | '?' | '*' => '_',
            c if c.is_control() => ' ',
            c => c,
        })
        .collect();
    let mut name = replaced.split_whitespace().collect::<Vec<_>>().join(" ");
    name = name.trim_matches(['.', ' ']).to_owned();
    let device = name
        .split('.')
        .next()
        .unwrap_or("")
        .trim()
        .to_ascii_uppercase();
    let reserved = matches!(device.as_str(), "CON" | "PRN" | "AUX" | "NUL")
        || ((device.starts_with("COM") || device.starts_with("LPT"))
            && device.len() == 4
            && device.as_bytes()[3].is_ascii_digit());
    if reserved {
        name.insert(0, '_');
    }
    name
}

fn of_kind<'b, 'a>(items: &'b [ExportItem<'a>], kind: ExportKind) -> Vec<&'b ExportItem<'a>> {
    items.iter().filter(|i| i.kind == kind).collect()
}

/// `# Title` and the authors' line.
fn title(out: &mut String, head: &ExportHead) {
    let _ = writeln!(out, "# {}\n", inline(&head.title));
    if !head.authors.trim().is_empty() {
        let _ = writeln!(out, "{}\n", inline(&head.authors));
    }
}

/// `Note: <note>` and an empty line, if there is a note.
fn note_paragraph(out: &mut String, note: Option<&str>) {
    if let Some(note) = note {
        let _ = writeln!(out, "Note: {}\n", plain(note.trim()));
    }
}

/// The text with one line break at its end.
fn finish(mut out: String) -> String {
    let trimmed = out.trim_end().len();
    out.truncate(trimmed);
    out.push('\n');
    out
}

/// Text for a single Markdown line (headings, list items): line breaks and other
/// whitespace, no-break spaces included, become single spaces.
fn inline(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Multi-line text (quotes, notes) with no-break spaces replaced by plain ones: some
/// editors show them as visible characters.
fn plain(text: &str) -> String {
    text.replace(['\u{a0}', '\u{202f}'], " ")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn head() -> ExportHead {
        ExportHead {
            title: "The\u{a0}Book".into(),
            authors: "A. Author".into(),
        }
    }

    fn item<'a>(
        kind: ExportKind,
        text: &'a str,
        note: Option<&'a str>,
        section: Option<&'a str>,
    ) -> ExportItem<'a> {
        ExportItem {
            kind,
            text,
            note,
            section_title: section,
            label: "The start of the line…".into(),
            href: "http://h/book/1/read?at=b3&from=mark".into(),
            lost: false,
        }
    }

    #[test]
    fn unlinked_quotes_notes_and_separators() {
        let items = [
            item(ExportKind::Bookmark, "", Some("Named"), Some("Chapter 1")),
            item(
                ExportKind::Quote,
                "First paragraph.\n\nSecond\u{a0}paragraph.",
                Some("A note\non two lines"),
                Some("Chapter 1"),
            ),
            item(
                ExportKind::Quote,
                "Without a note.",
                Some("  "),
                Some("Chapter 1"),
            ),
            item(
                ExportKind::Quote,
                "In the next one.",
                None,
                Some("Chapter 2"),
            ),
            item(ExportKind::Quote, "No section.", None, None),
            item(ExportKind::PlaceNote, "", Some("A thought"), None),
            item(
                ExportKind::PlaceNote,
                "",
                Some("Another"),
                Some("Chapter 2"),
            ),
        ];
        assert_eq!(
            unlinked(&head(), &items),
            "# The Book\n\nA. Author\n\n\
             ## Quotes\n\n\
             ### Chapter 1\n\n\
             First paragraph.\n\nSecond paragraph.\n\n\
             Note: A note\non two lines\n\n\
             ***\n\n\
             Without a note.\n\n\
             ***\n\n\
             ### Chapter 2\n\n\
             In the next one.\n\n\
             ***\n\n\
             No section.\n\n\
             ## Notes\n\n\
             The start of the line…\n\nNote: A thought\n\n\
             ***\n\n\
             The start of the line…\n\nNote: Another\n"
        );
    }

    #[test]
    fn unlinked_has_no_links_bookmarks_marker_or_block_quotes() {
        let items = [
            item(ExportKind::Bookmark, "", None, None),
            item(ExportKind::Quote, "Quoted", None, None),
        ];
        let md = unlinked(&head(), &items);
        assert!(!md.contains("http") && !md.contains("](") && !md.contains(MARKER));
        assert!(
            !md.contains("## Bookmarks") && !md.contains("## Notes"),
            "{md}"
        );
        assert!(!md.lines().any(|l| l.starts_with('>')), "{md}");
        assert!(!md.contains(SEPARATOR), "one record: no separator: {md}");
        let only_notes = unlinked(
            &ExportHead::default(),
            &[item(ExportKind::PlaceNote, "", Some("n"), None)],
        );
        assert_eq!(
            only_notes,
            "# \n\n## Notes\n\nThe start of the line…\n\nNote: n\n"
        );
    }

    #[test]
    fn linked_keeps_the_library_form() {
        let mut lost = item(ExportKind::Quote, "Elsewhere", None, Some("Chapter 2"));
        lost.lost = true;
        let items = [
            item(ExportKind::Bookmark, "", None, Some("Chapter 1")),
            item(ExportKind::Quote, "Quoted", Some("Mine"), Some("Chapter 1")),
            lost,
            item(ExportKind::PlaceNote, "", Some("A thought"), None),
        ];
        assert_eq!(
            linked(&head(), false, &items),
            format!(
                "{MARKER}\n\n# The Book\n\nA. Author\n\n\
                 ## Bookmarks\n\n- [The start of the line…](http://h/book/1/read?at=b3&from=mark)\n\n\
                 ## Quotes\n\n### Chapter 1\n\nQuoted\n\nMine\n\n\
                 [open](http://h/book/1/read?at=b3&from=mark)\n\n\
                 ### Chapter 2\n\nElsewhere\n\n\
                 [place not found](http://h/book/1/read?at=b3&from=mark)\n\n\
                 ## Notes\n\nA thought\n\n\
                 [The start of the line…](http://h/book/1/read?at=b3&from=mark)\n"
            )
        );
    }

    #[test]
    fn copy_text_of_one_quote() {
        assert_eq!(
            copy_text(&head(), "  Two\nlines\u{a0}here ", Some("A\nnote")),
            "Two\nlines here\n\nNote: A\nnote\n\n— A. Author, The Book"
        );
        let untitled = ExportHead {
            title: "T".into(),
            authors: String::new(),
        };
        assert_eq!(copy_text(&untitled, "Q", Some(" ")), "Q\n\n— T");
        assert_eq!(copy_text(&ExportHead::default(), "Q", None), "Q");
    }

    #[test]
    fn file_names() {
        assert_eq!(
            quotes_file_name(&head()),
            "A. Author — The Book — quotes.md"
        );
        assert_eq!(file_stem("com1.txt", ""), "_com1.txt");
        assert_eq!(file_stem("COMMA", ""), "COMMA");
        assert_eq!(file_stem("a\tb\nc*?<>|\"\\", "x"), "x — a b c_______");
        assert!(text::char_len(&file_stem(&"слово ".repeat(100), "")) <= MAX_STEM_CHARS);
    }
}
